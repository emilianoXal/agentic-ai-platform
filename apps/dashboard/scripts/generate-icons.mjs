// Extracts the Tabler outline icons the dashboard uses into a small TypeScript map,
// so the bundle ships only these icons instead of the whole set.
// Usage: node scripts/generate-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = [
  'inbox',
  'send',
  'tool',
  'circle-check',
  'circle-minus',
  'refresh',
  'bulb',
  'droplet',
  'traffic-cone',
  'trash',
  'ripple',
  'tree',
  'bug',
  'shield',
  'dots',
  'map-pin',
  'users',
  'x',
  'clock',
  'message-circle',
  'photo',
  'arrow-big-up-lines',
  'logout',
  'sun',
  'moon',
  'device-mobile',
  'player-play',
  'rotate',
  'user-plus',
  'alert-triangle',
  'filter',
  'chevron-right',
  'building-community',
  'route',
  'check',
  'eye',
  'eye-off',
];

const nodes = JSON.parse(
  readFileSync(
    new URL('../node_modules/@tabler/icons/tabler-nodes-outline.json', import.meta.url),
    'utf8',
  ),
);

const escapeAttr = (value) => String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const entries = NAMES.map((name) => {
  const icon = nodes[name];
  if (!icon) throw new Error(`Tabler icon not found: ${name}`);
  const markup = icon
    .map(([tag, attrs]) => {
      const attrText = Object.entries(attrs)
        .filter(([key]) => key !== 'key')
        .map(([key, value]) => `${key}="${escapeAttr(value)}"`)
        .join(' ');
      return `<${tag} ${attrText}/>`;
    })
    .join('');
  return `  '${name}': '${markup}',`;
});

const header =
  '// Generated by scripts/generate-icons.mjs from @tabler/icons (MIT). Do not edit by hand.\n';
writeFileSync(
  new URL('../src/app/shared/icons.generated.ts', import.meta.url),
  `${header}export const ICONS: Record<string, string> = {\n${entries.join('\n')}\n};\n\nexport type IconName = ${NAMES.map((n) => `'${n}'`).join(' | ')};\n`,
);
console.log(`Wrote ${NAMES.length} icons`);
